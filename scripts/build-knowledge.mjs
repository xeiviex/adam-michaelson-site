#!/usr/bin/env node
/**
 * Build the chat knowledge base from Notion, [PUBLIC] sections only.
 *
 *   NOTION_TOKEN=secret_xxx npm run knowledge
 *
 * Writes (both gitignored / generated, never committed):
 *   knowledge.md                       human-readable copy (repo root, gitignored)
 *   functions/_generated/knowledge.js  the module /api/chat imports
 *
 * The build FAILS (non-zero exit) if a page has zero [PUBLIC] sections, the private
 * notes page is referenced, or anything non-public shows up in the output.
 *
 * Local dry-run without a token:  node scripts/build-knowledge.mjs --from-dir <dir-of-.md>
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { blockedNames, allowedFullNames, redact } from "../functions/_lib/nameguard.js";
import { filterPage, assertNoLeak, markdownToBlocks } from "./lib/knowledge-filter.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export const PAGES = [
  ["3f52856e-f62e-817d-a0ce-e9f557411163", "Adam's Professional Biography"],
  ["3f52856e-f62e-8149-8ff5-cae56ee795e9", "Adam's Personal Biography"],
  ["3f52856e-f62e-81c5-a80f-f97a25e09a04", "Frameworks: Product Manager Competencies"],
  ["3f52856e-f62e-8189-86dc-e2ba2f2595f5", "Frameworks: Disciplined Product Management"],
  ["3f52856e-f62e-8178-902b-e763dd7a8310", "Frameworks: PM/UX Performance Management"],
  ["3f52856e-f62e-81d7-bbec-e8e834a3f45e", "Frameworks: Product Team Roles & Rules of Engagement"],
  ["3f52856e-f62e-81a4-b3f6-eeb9af22f832", "Frameworks: Product Team Roles & Expectations"],
];

// Hard-coded exclusion: "Adam's Professional Biography: Private Notes (NOT FOR PUBLIC CHAT)".
// This page is never fetched. Its id is only used to refuse and to scan the output.
export const PRIVATE_IDS = ["3f52856e-f62e-812e-848d-ea3a12ed1688"];

const fail = (msg) => {
  console.error("\nBUILD FAILED: " + msg);
  process.exit(1);
};

const fromDirIdx = process.argv.indexOf("--from-dir");
const fromDir = fromDirIdx > -1 ? process.argv[fromDirIdx + 1] : null;

for (const [id] of PAGES) {
  if (PRIVATE_IDS.some((p) => p.replace(/-/g, "") === id.replace(/-/g, ""))) fail(`private page ${id} is in the pull list`);
}

const sections = [];
const allDropped = [];
const fixtureFiles = fromDir ? readdirSync(fromDir).filter((f) => f.endsWith(".md")).sort() : null;

if (fromDir) {
  for (const f of fixtureFiles) {
    const r = filterPage(f.replace(/\.md$/, ""), markdownToBlocks(readFileSync(join(fromDir, f), "utf8")));
    if (r.publicSections === 0) fail(`"${f}" contains zero [PUBLIC] sections`);
    sections.push(r.markdown);
    allDropped.push(...r.dropped);
  }
} else {
  const token = process.env.NOTION_TOKEN;
  if (!token) fail("NOTION_TOKEN is not set (set it as a build environment variable in Cloudflare Pages).");
  const { pageTitle, pageBlocks } = await import("./lib/notion.mjs");
  for (const [id, fallback] of PAGES) {
    let title = fallback;
    try { title = (await pageTitle(id, token)) || fallback; } catch (e) { fail(`could not read page ${id}: ${e.message}`); }
    let blocks;
    try { blocks = await pageBlocks(id, token); } catch (e) { fail(`could not read blocks of "${title}": ${e.message}`); }
    const r = filterPage(title, blocks);
    if (r.publicSections === 0) fail(`"${title}" contains zero [PUBLIC] sections`);
    console.log(`  ${title}: ${r.publicSections} public sections, ${r.dropped.length} blocks excluded`);
    sections.push(r.markdown);
    allDropped.push(...r.dropped);
  }
}

const names = blockedNames(process.env);
const markdown = redact(sections.join("\n"), names, allowedFullNames(process.env));
const redactedCount = sections.join("\n").length !== markdown.length ? "yes" : "none found";
console.log(`blocked names removed from knowledge: ${redactedCount}`);
const canaries = (process.env.KNOWLEDGE_CANARIES || "").split("\n").map((s) => s.trim()).filter(Boolean);
try {
  assertNoLeak(markdown, { privateIds: PRIVATE_IDS, dropped: allDropped, canaries });
} catch (e) {
  fail(e.message);
}

const out = fromDir ? join(fromDir, "..", "knowledge.out.md") : join(root, "knowledge.md");
writeFileSync(out, markdown);
if (!fromDir) {
  writeFileSync(
    join(root, "functions/_generated/knowledge.js"),
    `// GENERATED by scripts/build-knowledge.mjs. Do not commit generated content.\nexport default ${JSON.stringify(markdown)};\n`
  );
}
console.log(`knowledge built: ${markdown.length} chars -> ${out}`);
